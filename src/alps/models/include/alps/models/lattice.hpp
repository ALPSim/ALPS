// Programmatic lattice construction: typed unit-cell vertices and offset
// edges, finite extents and per-dimension boundary conditions. Named factories
// build the standard geometries; edges() and site_types() supply the graph
// half of alps::models::CompiledModel.
//
// The tiling semantics are pinned by the frozen fixtures in
// tests/fixtures/lattice (see tests/lattice_kit_parity.cpp). The fixtures were
// generated by the alpsx Python lattice module and are kept as reference data.
// Load-bearing tiling semantics (parity contract with the Python module):
//   - cells enumerate in lexicographic order, LAST dimension fastest
//     (itertools.product), site index = cell_id * num_vertices + vertex;
//   - one bond per (cell, unit-cell edge) instance, NO unordered-pair
//     deduplication — matching the ALPS FINITELATTICE expansion
//     bond-for-bond (a periodic L=2 chain has TWO 0-1 bonds, the two
//     wrap images).
//     Self-bonds are dropped (a periodic L=1 chain has none — the one
//     remaining divergence: the legacy expansion emits a self-loop there);
//   - a bond `wraps` iff the periodic modulo actually moved an endpoint
//     cell; its `vector` is the in-cluster coordinate difference (NOT the
//     unwrapped displacement);
//   - open boundaries drop any edge whose endpoint cell falls outside the
//     extent.

