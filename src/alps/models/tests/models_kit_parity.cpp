lat::Lattice kondo_geometry(int L) {
    lat::UnitCell uc(1);
    uc.add_vertex({0.0}, 0);
    uc.add_vertex({0.5}, 1);
    uc.add_edge(0, 0, 0, {}, {1});
    uc.add_edge(0, 1, 1);
    return uc.tile({L});
}

