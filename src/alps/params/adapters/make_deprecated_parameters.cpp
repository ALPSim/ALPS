#include <alps/ngs/make_deprecated_parameters.hpp>

#include <string>

namespace alps {

    Parameters make_deprecated_parameters(params const & arg) {
        Parameters par;
        for (auto const & supplied : arg.supplied_text())
            par.push_back(supplied.first, supplied.second);
        return par;
    }
}
